/**
 * Нормалізація назви країни (повертає назву українською)
 */
export function normalizeCountry(rawCountry) {
  if (!rawCountry || typeof rawCountry !== "string") return "";
  const trimmed = rawCountry.trim();
  if (CITIES_BY_COUNTRY[trimmed]) return trimmed;

  const lower = trimmed.toLowerCase();
  if (COUNTRY_SYNONYMS[lower]) {
    return COUNTRY_SYNONYMS[lower];
  }

  // Спробуємо знайти по частковому співпадінню
  const found = EUROPEAN_COUNTRIES.find(
    (c) =>
      c.name.toLowerCase() === lower ||
      c.nameEn.toLowerCase() === lower ||
      c.code.toLowerCase() === lower,
  );

  return found ? found.name : trimmed;
}

/**
 * Отримати список міст для обраної країни
 * @param {string} country - назва країни (укр або англ)
 * @returns {Array<{ name: string, local: string, country: string }>}
 */
export function getCitiesByCountry(country) {
  const norm = normalizeCountry(country);
  if (norm && CITIES_BY_COUNTRY[norm]) {
    return CITIES_BY_COUNTRY[norm].map((city) => ({
      ...city,
      country: norm,
    }));
  }

  // Якщо країна не обрана — повертаємо топ європейських міст
  return getAllPopularCities();
}


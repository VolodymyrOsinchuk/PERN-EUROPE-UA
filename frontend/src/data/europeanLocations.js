/**
 * Пошук міст за фрагментом тексту (як українською, так і латиницею)
 */
export function searchCities(query, country = "") {
  const normCountry = normalizeCountry(country);
  const pool =
    normCountry && CITIES_BY_COUNTRY[normCountry]
      ? CITIES_BY_COUNTRY[normCountry].map((c) => ({
          ...c,
          country: normCountry,
        }))
      : Object.entries(CITIES_BY_COUNTRY).flatMap(([cName, list]) =>
          list.map((c) => ({ ...c, country: cName })),
        );

  if (!query || !query.trim()) {
    return pool.slice(0, 40);
  }

  const q = query.trim().toLowerCase();
  return pool
    .filter(
      (c) =>
        c.name.toLowerCase().includes(q) ||
        (c.local && c.local.toLowerCase().includes(q)),
    )
    .slice(0, 50);
}
